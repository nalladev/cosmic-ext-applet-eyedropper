#!/usr/bin/env python3
"""Release workflow, run via `just release VERSION`.

1. First run for a version: add an empty <release> entry to the <releases>
   section of resources/app.metainfo.xml, then stop so you can write the
   description by hand.
2. Run it again: the script checks that the description is not empty, bumps
   Cargo.toml, runs the CI checks, commits "release: VERSION", tags "vVERSION"
   and pushes the commit and tag together (which triggers the release workflow).

Nothing is ever reverted. If a step fails, fix the problem and run the same
command again; steps that are already done are skipped.
"""

import datetime
import os
import re
import shlex
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import NoReturn
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
os.chdir(ROOT)

METAINFO = Path("resources/app.metainfo.xml")
CARGO = Path("Cargo.toml")
MANIFEST = "io.github.nalladev.CosmicExtAppletEyedropper.json"
REMOTE = "origin"
BRANCH = "main"

# Mirrors .github/workflows/ci.yml. Skipped on purpose: generating
# cargo-sources.json (needs network, regenerated by the release workflow) and
# flatpak-builder-lint (needs docker). AppStream is validated with --no-net
# because the release tag (and so the release URL) does not exist yet.
CHECKS = [
    ("clippy (just lint)", ["just", "lint"], False),
    ("Flatpak manifest", ["flatpak-builder", "--show-manifest", MANIFEST], True),
    ("AppStream metadata", ["appstreamcli", "validate", "--no-net", str(METAINFO)], False),
]


def die(message: str) -> NoReturn:
    sys.exit(f"\nrelease: {message}")


def run(cmd: list[str], *, quiet: bool = False) -> int:
    """Run a command with inherited stdio and return its exit code."""
    print(f"$ {shlex.join(cmd)}", flush=True)
    return subprocess.run(
        cmd, stdout=subprocess.DEVNULL if quiet else None, check=False
    ).returncode


def git(*args: str) -> str:
    """Run a git command and return its stdout; abort the release on failure."""
    result = subprocess.run(["git", *args], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        die(f"`git {' '.join(args)}` failed:\n{result.stderr.strip()}")
    return result.stdout.strip()


def git_ok(*args: str) -> bool:
    return subprocess.run(["git", *args], capture_output=True, check=False).returncode == 0


def repo_url() -> str:
    match = re.search(r'(?m)^repository\s*=\s*"([^"]+)"', CARGO.read_text())
    if not match:
        die("no `repository` field found in Cargo.toml")
    return match.group(1).removesuffix(".git").rstrip("/")


# --- Metainfo release entry ----------------------------------------------------


def release_elements(version: str) -> list[ET.Element]:
    try:
        root = ET.fromstring(METAINFO.read_text(encoding="utf-8"))
    except ET.ParseError as err:
        die(f"{METAINFO} is not valid XML: {err}")
    return [r for r in root.iter("release") if r.get("version") == version]


def add_release(version: str) -> None:
    """Insert an empty <release> at the top of <releases> in the metainfo."""
    text = METAINFO.read_text(encoding="utf-8")
    existing = re.search(r"^([ \t]*)<release\b", text, re.MULTILINE)
    pad = existing.group(1) if existing else "  "
    date = datetime.date.today().isoformat()
    url = escape(f"{repo_url()}/releases/tag/v{version}")

    release = (
        f'{pad}<release version="{version}" date="{date}">\n'
        f"{pad}  <description>\n"
        f"{pad}    <ul>\n"
        f"{pad}      <li></li>\n"
        f"{pad}    </ul>\n"
        f"{pad}  </description>\n"
        f'{pad}  <url type="details">{url}</url>\n'
        f"{pad}</release>\n"
    )

    if re.search(r"<releases\s*>[ \t]*\n", text):
        updated = re.sub(
            r"(<releases\s*>[ \t]*\n)", lambda m: m.group(1) + release, text, count=1
        )
    elif re.search(r"<releases\s*/>", text):
        updated = re.sub(
            r"<releases\s*/>", lambda _m: f"<releases>\n{release}</releases>", text, count=1
        )
    elif "</component>" in text:
        block = f"  <releases>\n{release}  </releases>\n"
        updated = text.replace("</component>", block + "</component>", 1)
    else:
        die(f"could not find where to add the release in {METAINFO}")

    try:
        ET.fromstring(updated)
    except ET.ParseError as err:
        die(f"adding the release would break {METAINFO} ({err}); left unchanged")
    METAINFO.write_text(updated, encoding="utf-8")


def description_filled(version: str) -> bool:
    matches = release_elements(version)
    if len(matches) != 1:
        die(f"expected exactly one <release version=\"{version}\"> in {METAINFO}, found {len(matches)}")
    description = matches[0].find("description")
    return description is not None and "".join(description.itertext()).strip() != ""


# --- Version bump, checks, commit, tag, push ----------------------------------------


def sync_cargo(version: str) -> None:
    text = CARGO.read_text(encoding="utf-8")
    match = re.search(r'(?ms)^\[package\]\s*$.*?^version\s*=\s*"([^"]+)"', text)
    if not match:
        die("could not find the package version in Cargo.toml")
    if match.group(1) == version:
        print(f"{CARGO} is already at {version}.")
        return
    text = text[: match.start(1)] + version + text[match.end(1) :]
    CARGO.write_text(text, encoding="utf-8")
    print(f"Bumped {CARGO} from {match.group(1)} to {version} (Cargo.lock updates during checks).")


def run_checks() -> None:
    print("\nRunning the CI checks...")
    for name, cmd, quiet in CHECKS:
        if run(cmd, quiet=quiet) != 0:
            die(
                f"check failed: {name}.\n"
                "Nothing was reverted. Fix the problem, then re-run "
                "`just release` with the same version to re-check."
            )
        print(f"ok: {name}\n")


def preflight_fresh(tag: str) -> None:
    """Extra safety before a brand new release touches any file."""
    if git("status", "--porcelain"):
        die("working tree must be clean before starting a new release; commit or stash first")
    if git_ok("rev-parse", "-q", "--verify", f"refs/tags/{tag}"):
        die(f"tag {tag} already exists locally")
    print(f"Checking {REMOTE}...")
    git("fetch", REMOTE, BRANCH)
    if git_ok("ls-remote", "--exit-code", "--tags", REMOTE, f"refs/tags/{tag}"):
        die(f"tag {tag} already exists on {REMOTE}")
    behind = git("rev-list", "--count", f"HEAD..{REMOTE}/{BRANCH}")
    if behind != "0":
        die(f"local {BRANCH} is {behind} commit(s) behind {REMOTE}/{BRANCH}; pull first")


def commit_release(version: str) -> None:
    git("add", "-A")
    print("\nChanges in the release commit:")
    print(git("status", "--short"))
    if not git("status", "--porcelain"):
        die("there is nothing to commit for this release")
    git("commit", "-m", f"release: {version}")
    print(f"Committed release: {version}.")


def create_tag(tag: str, version: str) -> None:
    if git_ok("rev-parse", "-q", "--verify", f"refs/tags/{tag}"):
        if git("rev-list", "-n", "1", tag) != git("rev-parse", "HEAD"):
            die(f"tag {tag} already exists but does not point at the release commit")
        print(f"Tag {tag} already exists on the release commit.")
        return
    git("tag", "-a", tag, "-m", f"Release {version}")
    print(f"Created tag {tag}.")


def push(tag: str) -> None:
    print("\nPushing the release commit and tag...")
    # --atomic: either both refs update or neither does.
    if run(["git", "push", "--atomic", REMOTE, f"refs/heads/{BRANCH}", f"refs/tags/{tag}"]) != 0:
        die(
            "push failed. The release commit and tag are intact locally; "
            "fix the problem and re-run `just release` with the same version to push again."
        )


def main() -> None:
    if len(sys.argv) != 2:
        die("usage: just release VERSION")

    version = sys.argv[1].strip().removeprefix("v")
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        die(f"version must look like 1.2.3 (got {sys.argv[1]!r})")
    tag = f"v{version}"

    if git("rev-parse", "--abbrev-ref", "HEAD") != BRANCH:
        die(f"releases must be made from {BRANCH}")

    if git("log", "-1", "--format=%s") == f"release: {version}":
        # An earlier run already committed (and maybe tagged); only the push is left.
        if git("status", "--porcelain"):
            die("HEAD is the release commit but the working tree has changes; "
                "commit them (e.g. `git commit --amend`) or stash them first")
        print(f"Release commit for {version} already exists; skipping the checks.")
    else:
        if not release_elements(version):
            preflight_fresh(tag)
            add_release(version)
            die(
                f"added an empty release {version} to {METAINFO}.\n"
                f"Write the release notes in its <description> (replace the empty <li></li>), "
                f"then run `just release {version}` again."
            )
        if not description_filled(version):
            die(
                f"the description of release {version} in {METAINFO} is still empty.\n"
                f"Fill it in, then run `just release {version}` again."
            )
        sync_cargo(version)
        run_checks()
        commit_release(version)

    create_tag(tag, version)
    push(tag)
    print(f"\nReleased {tag}. The release workflow is now running on GitHub.")


if __name__ == "__main__":
    main()
